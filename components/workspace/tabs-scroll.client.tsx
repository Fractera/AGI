"use client"

import { useEffect } from "react"

// ПЛАВНАЯ ПРОКРУТКА ПО ВЕРХНЕМУ РЯДУ СТРАНИЦЫ (264-4).
//
// 🔒 ЗАЧЕМ ОН ЕСТЬ, ЕСЛИ ЕСТЬ `scroll-smooth`. Решение владельца 2026-09-21:
// «это просто кнопки быстрой навигации по текущей длинной странице, просто
// анимированная прокрутка». `scroll-smooth` на `<html>` стоит и отвечает за
// плавность — но самого перехода к якорю на этих страницах НЕ ПРОИСХОДИТ:
// измерено, адрес меняется на `#anchor`, а `window.scrollY` остаётся нулём.
//
// 🛑 ЭТО ОБХОД, А НЕ ЛЕЧЕНИЕ КОРНЯ, И ТАК ЭТО И НАЗЫВАЕТСЯ. Отказ шире ряда и
// шире слоя: на публичной странице `/ru/m2m` переход по `#` к заголовку тоже не
// прокручивает. Причина не найдена, и списывать её на догадку запрещено;
// `element.scrollIntoView()` при этом работает — на нём и стоит этот островок.
// Общий дефект записан долгом: пока он жив, НИ ОДНА ссылка на раздел страницы
// не приводит туда, куда обещает, — включая те, что люди пересылают друг другу.
//
// 🔒 ЭТО УЛУЧШЕНИЕ, А НЕ УСЛОВИЕ РАБОТЫ. Разметка ряда остаётся обычными
// `<a href="#…">`: без JavaScript они ведут себя так, как позволит браузер, и
// ничего не ломается. Островок не владеет маршрутом и ничего не рисует.
//
// 🔒 СЛУШАТЕЛЬ ОДИН, ДЕЛЕГИРОВАННЫЙ, И ТОЛЬКО НА СВОЁМ РЯДУ. Вешать обработчик
// на каждую кнопку значит завести столько же подписок, сколько тем на странице,
// и снимать их поодиночке; попасть же он должен только в свой ряд — остальные
// якоря страницы чинятся вместе с корнем, а не здесь.
export function TabsScroll() {
  useEffect(() => {
    const onClick = (e: MouseEvent) => {
      // Клик с модификатором или не левой кнопкой — это «открыть иначе»,
      // и перехватывать его нельзя.
      if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return

      const link = (e.target as Element | null)?.closest?.('[data-workspace-tabs] a[href^="#"]')
      if (!(link instanceof HTMLAnchorElement)) return

      const id = decodeURIComponent(link.hash.slice(1))
      const target = id ? document.getElementById(id) : null
      if (!target) return

      e.preventDefault()

      // 🛑 ПЛАВНАЯ ПРОКРУТКА БЫВАЕТ ИНЕРТНОЙ, И ТОГДА ОНА НЕ ЗАМЕДЛЯЕТ ПЕРЕХОД,
      // А ОТМЕНЯЕТ ЕГО ЦЕЛИКОМ. Измерено 2026-09-21 в браузере владельца на этой
      // самой странице: `scrollIntoView({behavior:'instant'})` перемещает на 2559
      // пикселей, `{behavior:'smooth'}` не двигает вовсе, `prefers-reduced-motion`
      // при этом `false`. Отсюда и прежний отказ всех якорей слоя: `scroll-smooth`
      // на `<html>` делает плавным и НАТИВНЫЙ переход по `#`, а инертная плавность
      // превращает его в смену адреса без движения.
      //
      // 🔒 ПОЭТОМУ ПРОСИМ ПЛАВНО, НО ПРОВЕРЯЕМ ФАКТОМ. Через кадр смотрим, сдвинулась
      // ли страница; не сдвинулась — везём мгновенно. Человек попадает в раздел
      // ВСЕГДА, а анимация остаётся там, где браузер её умеет. Это ровно тот случай,
      // когда способность спрашивают у самой способности, а не у её объявления.
      const before = window.scrollY
      target.scrollIntoView({ behavior: "smooth", block: "start" })
      window.setTimeout(() => {
        if (Math.abs(window.scrollY - before) < 2) {
          target.scrollIntoView({ behavior: "auto", block: "start" })
        }
      }, 150)

      // Адрес обновляется без записи в историю: ряд — это навигация по одной
      // странице, и двадцать нажатий не должны превращаться в двадцать шагов
      // «назад». Зазор под липкой полосой даёт `scroll-mt-24` у заголовка.
      history.replaceState(null, "", `#${id}`)
    }

    document.addEventListener("click", onClick)
    return () => document.removeEventListener("click", onClick)
  }, [])

  return null
}
