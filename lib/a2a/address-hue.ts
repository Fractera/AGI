// ЦВЕТ АГЕНТА ИЗ ЕГО АДРЕСА (шаг 408; владелец: «субдомен можно было бы каким-то образом перегонять в идентификатор цвета,
// чтобы не придумывать новую функцию и стабилизировать цвет каждый раз»). Адрес → FNV-1a → оттенок 0–359. Один адрес —
// всегда один оттенок, на любой машине и после перезагрузки; насыщенность и яркость задаёт тема (лента: светлая и тёмная).
export function addressHue(address: string): number {
  let h = 0x811c9dc5
  for (let i = 0; i < address.length; i++) {
    h ^= address.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0) % 360
}
