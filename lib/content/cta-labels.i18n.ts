export type CtaLabels = {
  /** Первое действие: поставить агента-программиста. */
  install: string
  /** Второе: подключить к нему подписку внутри собственного узла. */
  build: string
}

const EN: CtaLabels = {
  install: 'Install Claude Code',
  build: 'Start building',
}

const RU: CtaLabels = {
  install: 'Установить Claude Code',
  build: 'Начать строить',
}

export function ctaLabels(lang: string): CtaLabels {
  return lang === 'ru' ? RU : EN
}
