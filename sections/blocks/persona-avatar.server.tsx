import type { Persona } from '@/lib/content/blocks/types'

// ТРИ ЛИЦА ДЛЯ ПЕРЕКЛЮЧАТЕЛЯ ЛИЧНОСТЕЙ — встроенный рисунок, а не файл.
//
// 🎯 Заказ владельца 2026-09-21: «в левой части круглая аватар-иконка человек — например,
// девушка, или мужчина без усов, или мужчина с усами».
//
// 🔒 РИСУНОК ЖИВЁТ ТОКЕНАМИ ТЕМЫ (`currentColor`), поэтому он верен в обеих темах и
// подчиняется подсветке выбранной карточки: выбранная личность получает цвет `primary`,
// остальные — приглушённый. Фотография участника потребовала бы файла на каждый язык
// продукта, а чужая библиотека лиц — зависимости ради трёх значков.
//
// 🔒 ЛИЦО — ЗНАЧОК, А НЕ СОДЕРЖАНИЕ: оно скрыто от читалки экрана (`aria-hidden`), потому
// что рядом стоят имя и роль — то, что человеку действительно нужно услышать.

export function PersonaAvatar({ face }: { face: Persona['face'] }) {
  return (
    <svg
      aria-hidden
      className="size-10 shrink-0 rounded-full border border-current/30 bg-current/5 p-0.5"
      fill="none"
      stroke="currentColor"
      strokeLinecap="round"
      strokeLinejoin="round"
      strokeWidth="1.6"
      viewBox="0 0 32 32"
    >
      {/* Голова и плечи — общие у всех трёх лиц. */}
      <circle cx="16" cy="12" r="6" />
      <path d="M5.5 27c1.6-5.2 5.6-7.8 10.5-7.8S24.9 21.8 26.5 27" />

      {/* Длинные волосы: две пряди по бокам головы. */}
      {face === 'long-hair' && (
        <path d="M9.4 9.2c.6-3.4 3.2-5.2 6.6-5.2s6 1.8 6.6 5.2M9.6 8.4c-1.2 3.4-1.4 7-.6 10.4M22.4 8.4c1.2 3.4 1.4 7 .6 10.4" />
      )}

      {/* Без усов: короткая линия волос надо лбом. */}
      {face === 'plain' && <path d="M10.4 9c1.2-2.2 3.2-3.2 5.6-3.2s4.4 1 5.6 3.2" />}

      {/* С усами: та же линия волос плюс усы под носом. */}
      {face === 'moustache' && (
        <path d="M10.4 9c1.2-2.2 3.2-3.2 5.6-3.2s4.4 1 5.6 3.2M12.6 14.4c1-.8 2-1.2 3.4-1.2s2.4.4 3.4 1.2" />
      )}
    </svg>
  )
}
