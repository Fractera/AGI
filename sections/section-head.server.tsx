import type { ReactNode } from 'react'
import { H2, Lead } from '@/components/ui/typography'
import { badgeClass } from '@/sections/tone'

// ШАПКА САМОСТОЯТЕЛЬНОГО РАЗДЕЛА — ОДНА НА ВСЕ РАЗДЕЛЫ СТРАНИЦЫ.
//
// 🔒 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Ярлык, заголовок и подзаголовок повторяются у трёх
// видов (`flow`, `cards`, `noBill`), и владелец трижды за день просил привести их
// «к одному стандарту» — потому что каждый раз я собирал шапку заново и она
// каждый раз выходила чуть иначе. Пока форма живёт в трёх местах, «одна
// анатомия» держится на моей памяти, а память — не механизм. Здесь она держится
// импортом.
//
// 🔒 ЦВЕТ ЯРЛЫКА РЕШАЕТ ЭТОТ ФАЙЛ, А НЕ МАТЕРИАЛ. Ярлык раздела — это НАЗВАНИЕ
// РУБРИКИ («Процесс», «Архитектура»), а не смысловая группа возможности: у него
// нет своих «данных» или «доступа», к которым можно привязать цвет. Поэтому
// материал несёт только СЛОВО (`badge?: string`), а тон один на все разделы —
// иначе владельцу пришлось бы держать `tone: 'data'` в десяти языковых ячейках
// каждого раздела и менять цвет в пятидесяти местах.
//
// Тон `data` выбран сознательно: он зелёный в обеих темах и не занят на этой
// странице ничем спорным. Меняется одним словом здесь.
const SECTION_BADGE_TONE = 'data' as const

export function SectionHead({
  id,
  badge,
  title,
  note,
}: {
  id: string
  badge?: string
  title: string
  /** Уже разобранный подзаголовок: инлайн-разметку раскрывает вызывающая секция. */
  note?: ReactNode
}) {
  // 🔒 ЗАГОЛОВКИ ВЫРОВНЕНЫ ПО ЛЕВОМУ КРАЮ — ОДНО ПРАВИЛО НА ВЕСЬ ПРОДУКТ
  // (решение владельца 2026-09-19, найдено им глазами: «у тебя половина
  // заголовков выровнена по левому краю а половина идёт по центру… поправь»).
  //
  // 🛑 ПРИЧИНА РАСХОЖДЕНИЯ БЫЛА НЕ В УРОВНЕ ЗАГОЛОВКА, как выглядело снаружи, а в
  // ДВУХ ИСТОЧНИКАХ одного и того же H2: самостоятельный блок `h2` рисовал его по
  // левому краю, а шапка раздела — по центру. На одной странице встречались оба,
  // и разница читалась как беспорядок, потому что беспорядком и была.
  //
  // 🔒 ПОЧЕМУ ЛЕВЫЙ КРАЙ, А НЕ ЦЕНТР. Центр достался от витринной вёрстки, где
  // раздел — плакат. Здесь страницы читают: глаз возвращается к одной вертикали,
  // и длинный заголовок в две строки по центру рвёт её дважды. Левый край
  // совпадает с H1, с текстом, с карточками и со слоем архитектора — то есть со
  // всем остальным продуктом.
  return (
    <div className="flex flex-col">
      {badge && (
        <span className={`mb-4 self-start ${badgeClass(SECTION_BADGE_TONE)}`}>{badge}</span>
      )}
      <H2 id={id}>{title}</H2>
      {note && <Lead className="mt-3 max-w-2xl">{note}</Lead>}
    </div>
  )
}
