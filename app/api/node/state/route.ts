// @api report how this node is reachable and whether it is walled off
import { NextRequest, NextResponse } from "next/server"

import { requireRoles } from "@/lib/auth/require-roles"
import { measureNodeState } from "@/lib/node-state/measure"

// СОСТОЯНИЕ УЗЛА ОДНОЙ ДВЕРЬЮ (276-1).
//
// 🔒 ЗАЧЕМ ДВЕРЬ, ЕСЛИ ВСЁ ЭТО МОЖНО ПРОЧИТАТЬ СЕРВЕРНЫМ КОМПОНЕНТОМ. Главная страница слоя
// архитектора ПРЕДРЕНДЕРЕНА: состояние, прочитанное на сборке, запечётся в HTML и останется там
// навсегда. Это тот же класс, за который проект уже платил в 264 («прибор, печатающий запомненное
// значение, врёт именно тогда, когда на него полагаются»), только дороже: там врал номер порта, здесь
// врало бы утверждение «ваш сайт виден в интернете». Поэтому состояние спрашивают в браузере.
//
// 🔒 `force-dynamic` ЗДЕСЬ ЗАКОНЕН И ОБЯЗАТЕЛЕН — это маршрут данных, а не страница публичного слоя.
// Застывший ответ о состоянии есть та же запечённая ложь, только этажом ниже.
//
// 🔒 ДВЕРЬ ЗАКРЫТА ВОРОТАМИ, И ЭТО РЕШЕНИЕ, А НЕ УПУЩЕНИЕ. Её имени НЕТ в `PUBLIC_API_PREFIXES`
// (`proxy.ts`) намеренно: здесь адреса узла, его порт, хэш сборки и номер процесса — сведения о машине
// человека, а не о продукте. Проходят те же, кто и к прочим дверям: хозяин за клавиатурой этой машины
// и вошедший по сессии.
//
// 🛑 ОТВЕТ ВСЕГДА НАЗЫВАЕТ ИСТОЧНИК КАЖДОГО СВЕДЕНИЯ (`measured` · `declared` · `unknown`). Половина
// состояния измеряется сетью, половина объявлена человеком, и показывать их с одинаковой
// уверенностью значит врать видом. `unknown` — это «не знаю», а не «нет».
// 🛑 РОЛЬ ПРОВЕРЯЕТСЯ ЗДЕСЬ, А НЕ ТОЛЬКО ВОРОТАМИ. ✗ Оплачено в тот же день, измерением: ворота
// `proxy.ts` пропускают ЛЮБОГО вошедшего, и живая сессия владельца на домене оказалась с ролью
// `user` — то есть адрес узла, порт, номер процесса и хэш сборки отдавались рядовому пользователю.
// Двухслойная проверка — закон проекта, и вторая половина стоит одной строки.
export const dynamic = "force-dynamic"

const ROLES = ["architect", "admin"] as const

export async function GET(req: NextRequest) {
  const denied = await requireRoles(req, ROLES)
  if (denied) return denied
  const state = await measureNodeState()
  return NextResponse.json({ ok: true, ...state }, { headers: { "Cache-Control": "no-store" } })
}
