import type { Block } from '@/lib/content/blocks/types'
import { googleSetupWords } from '@/components/auth/google-setup.i18n'

// СОДЕРЖИМОЕ СТРАНИЦЫ «Sign in with Google» (265-2).
//
// 🔒 ЗДЕСЬ РАБОТАЮЩАЯ ЧАСТЬ, А В `_data` — СЛОВА СТРАНИЦЫ. Экран включения —
// переиспользуемая часть со своим словарём рядом с собой: тот же вид годится
// соседнему разделу «Письмо-ключ (Resend)» и любому провайдеру, чьи ключи выдаёт
// кто-то чужой. Поэтому его слова приходят от него, а не отсюда и не из `_data`.
//
// 🔒 ЯЗЫК ВЫБИРАЕТСЯ ЗДЕСЬ, НА СЕРВЕРЕ, И В БЛОК УХОДИТ ОДИН НАБОР СТРОК. Отдай
// мы островку весь словарь — он уехал бы в браузер целиком, и это поймал бы
// сторож `check:lang-delivery`.
//
// 🔒 ЭКРАН СТОИТ ПЕРЕД ТЕКСТОМ, И ЭТО НЕ ВКУС. Оболочка складывает содержимое в
// порядке «работающая часть, потом темы»: человек приходит сюда действовать, а
// текст объясняет то, что он уже видит.
export function content(lang: string): Block[] {
  return [{ kind: 'authGoogleSetup', words: googleSetupWords(lang) }]
}
