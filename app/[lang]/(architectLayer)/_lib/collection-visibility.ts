// Страница, стоящая в карте сайта и отвечающая чужому 404, — не просто бесполезная
// строка: карта, обещающая то, чего нет, обесценивает всю карту, а набор адресов
// «для поисковика, но не для человека» и есть определение дорвея. Поэтому здесь
// ровно один источник правды, и он же решает три вещи сразу: мета-тег robots,
// присутствие в карте сайта и наличие альтернативных языковых адресов.

/**
 * Открыт ли слой архитектора всем.
 *
 * Сегодня — нет: слой закрыт ролью `architect`, и `proxy.ts` отвечает чужому 404.
 * Переключается ОДНОЙ этой строкой, и вместе с ней согласованно меняются карта
 * сайта, `robots.txt` и мета-теги каждой страницы.
 *
 * 🔒 ПОЧЕМУ КОНСТАНТА, А НЕ ЧТЕНИЕ КОНФИГА В РАНТАЙМЕ. Карта сайта и `robots.txt`
 * собираются статически; читай они настройку на каждый запрос, обе страницы ушли
 * бы в динамику — запрещено каноном статики. Когда настройка появится в панели,
 * она будет записываться в этот файл при сборке, как это уже сделано с другими
 * значениями слоя.
 */
export const ARCHITECT_LAYER_IS_PUBLIC = false

/**
 * Адреса страниц слоя для карты сайта.
 *
 * Пусто, пока слой закрыт, — и это не заглушка, а единственный честный ответ:
 * закрытая страница в карте сайта есть ложь поисковику.
 */
export function architectSitemapPaths(paths: readonly string[]): readonly string[] {
  return ARCHITECT_LAYER_IS_PUBLIC ? paths : []
}
