import { isShowcaseBuild } from '@/lib/showcase.server'

// ВИДИМОСТЬ КОЛЛЕКЦИИ — ОДИН ПЕРЕКЛЮЧАТЕЛЬ НА ВЕСЬ ШАБЛОН (255).
//
// 🔒 РЕШЕНИЕ ВЛАДЕЛЬЦА 2026-09-19, дословно: «я хочу сделать этот компонент
// универсальный, чтобы его можно было переиспользовать в том числе в публичном
// слое, если в настройках архитекторы отключат ограничения доступа. Другими
// словами, это максимально полный шаблон».
//
// 🛑 ПОЭТОМУ `noindex` ЗДЕСЬ НЕ ЗАШИТ, А ВЫЧИСЛЯЕТСЯ. Первая редакция ставила его
// константой — и шаблон переставал быть шаблоном: перенесённый в публичный слой,
// он унёс бы с собой запрет на индексацию, причём молча.
//
// 🛑 И ГЛАВНОЕ, ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ: ОБЪЯВЛЯТЬ ВИДИМЫМ ТО, ЧТО ЗАКРЫТО ЗАМКОМ.
// Страница, стоящая в карте сайта и отвечающая чужому 404, — не просто бесполезная
// строка: карта, обещающая то, чего нет, обесценивает всю карту, а набор адресов
// «для поисковика, но не для человека» и есть определение дорвея. Поэтому здесь
// ровно один источник правды, и он же решает три вещи сразу: мета-тег robots,
// присутствие в карте сайта и наличие альтернативных языковых адресов.

/**
 * Открыт ли слой архитектора всем.
 *
 * 🔒 ВЫВОДИТСЯ ИЗ АДРЕСА САЙТА, А НЕ ОБЪЯВЛЯЕТСЯ (256-2). Истина ровно на витрине
 * `fractera.ai` — решение владельца 2026-09-20: «проиндексируем слой архитектора и
 * одновременно индексируемый слой приватных страниц… только у Fractera». У гостя,
 * скопировавшего репозиторий, домен другой, поэтому тот же код закрывает его слой
 * по умолчанию, и никаких «отдельных прав» заводить не нужно.
 *
 * 🔒 ОДИН ОТВЕТ РЕШАЕТ ТРИ ВЕЩИ СРАЗУ: мета-тег `robots`, присутствие в карте
 * сайта и наличие альтернативных языковых адресов. Разведи их — и появится
 * состояние «в карте есть, а человеку 404», то есть дорвей.
 *
 * 🪦 ЗДЕСЬ СТОЯЛА КОНСТАНТА `false` И ДОВОД «читай мы конфиг, страницы ушли бы в
 * динамику». Довод опровергнут измерением: `app/robots.ts` и `app/sitemap.ts`
 * **уже** зовут `getAppConfig()` — первый за списком `disallow`, второй за адресом
 * сайта, — и обе страницы статические (`force-static` + `revalidate`). То есть
 * источник тот же, что они читали и до этой правки; нового чтения не появилось.
 */
export function architectLayerIsPublic(): boolean {
  return isShowcaseBuild()
}

/**
 * Адреса страниц слоя для карты сайта.
 *
 * Пусто, пока слой закрыт, — и это не заглушка, а единственный честный ответ:
 * закрытая страница в карте сайта есть ложь поисковику.
 */
export function architectSitemapPaths(paths: readonly string[]): readonly string[] {
  return architectLayerIsPublic() ? paths : []
}
