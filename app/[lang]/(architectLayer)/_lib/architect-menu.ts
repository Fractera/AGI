// Удалена 2026-09-19 (253) решением владельца: разделы переехали в подменю левого
// меню, а верхний ряд принадлежит навигации по самой странице. Страница отдаёт
// свой ряд сама — полем `tabs` оболочки; не отдала — ряда нет вовсе, и это
// законное состояние раздела, у которого ещё нет собственных тем.
//
// 🔒 ПОЧЕМУ УДАЛЕНА, А НЕ ОСТАВЛЕНА «НА ВСЯКИЙ СЛУЧАЙ»: оставшись, она была бы
// вторым устройством для верхнего ряда, и следующая страница выбрала бы наугад.
