import type { ReactNode } from 'react'
import type { Block, WorkspaceItem } from '@/lib/content/blocks/types'
import { type WorkspacePageData, pagesInOrder, wordsOf } from '@/lib/collection/types'
import { ArchitectPage } from './architect-page'
import { architectLayerUi } from '../_i18n/architect-layer.i18n'

// РУБРИКАТОР ГРУППЫ — страница, которая перечисляет своих детей (254).
//
// 🔒 СПИСОК НЕ ПИШЕТСЯ РУКАМИ НИКОГДА. Он приходит из `_list.generated.ts`,
// который сборка складывает из самих папок. Добавили папку — строка появилась;
// удалили — исчезла. Расходиться списку и диску негде: это одно и то же знание.
//
// 🔒 ГРУППА — ТАКАЯ ЖЕ СТРАНИЦА-ПАПКА, КАК ЕЁ РАЗДЕЛЫ. Свои слова она берёт из
// своего `_data`, а не из общего словаря слоя; различает её и раздел только
// глубина, и потому второй уровень не стоил ни одной строки в сканере.
//
// 🔒 ПОРЯДОК — ПО `meta.order`, А НЕ ПО ИМЕНИ ПАПКИ. У блога эту роль играет
// дата; у страниц слоя даты нет, и без явного поля порядок задавал бы алфавит —
// то есть переименование папки молча перетасовало бы меню.
//
// 🛑 РАЗДЕЛ БЕЗ СЛОВ ВСЁ РАВНО НАЗВАН. Пропускать такие в списке нельзя: пункт
// меню без строки в рубрикаторе есть то самое расхождение двух половин, ради
// которого всё это и строилось.

export function CollectionIndex({
  lang,
  dir,
  page,
  pages,
  content,
  widget,
}: {
  lang: string
  /** Адрес этой папки без языка, например `/architect/tools`. */
  dir: string
  /** Сама группа: её заголовок и подзаголовок лежат в её же `_data`. */
  page: WorkspacePageData
  /** Дети: ровно `PAGES` из порождённого списка этой папки. */
  pages: readonly WorkspacePageData[]
  /**
   * Содержимое из `_components/` этой группы — то, что идёт ПЕРЕД перечнем
   * разделов: сводка, показатели, кнопка действия.
   *
   * 🔒 ПУСТО — ЗАКОННО: у группы всегда есть что показать, её перечень детей.
   * Поэтому заглушки «скоро будет построено» здесь нет и быть не должно.
   */
  content?: Block[]
  /** Собственный островок маршрута (271) — рисуется в рабочем экране над списком разделов. */
  widget?: ReactNode
}) {
  const ui = architectLayerUi(lang)
  const words = wordsOf(page, lang)
  const ordered = pagesInOrder(pages)

  // 🔒 СТРОКА РУБРИКАТОРА — `docref`, А НЕ ПУНКТ СПИСКА. У неё есть имя, описание
  // и адрес, то есть ровно то, из чего состоит запись каталога; простой список
  // отдал бы одни имена, и человеку пришлось бы открывать разделы по очереди,
  // чтобы понять, куда ему надо.
  const children: Block[] = ordered.map((p) => {
    const w = wordsOf(p, lang)
    return {
      kind: 'docref',
      title: w.title,
      summary: w.lead ?? ui.emptyLead,
      // 291: переход, а не скачивание; адрес — чистый (285-6: страницы архитектора от корня ядра, без `/architect`).
      href: `/${lang}${dir.replace(/^\/architect(?=\/|$)/, '')}/${p.meta.slug}`,
      label: ui.openSection,
      navigate: true,
    }
  })

  // 🔒 ВЕРХНИЙ РЯД — ЭТО БЫСТРАЯ НАВИГАЦИЯ ПО ЭТОЙ ЖЕ СТРАНИЦЕ, А НЕ ПЕРЕХОДЫ.
  //
  // Решение владельца, повторённое им не в первый раз (2026-09-21, дословно):
  // «эти кнопки не должны дублировать левое меню, это просто кнопки быстрой
  // навигации по текущей длинной странице, просто анимированная прокрутка».
  //
  // 🪦 ЗДЕСЬ РЯД СОБИРАЛСЯ ИЗ РАЗДЕЛОВ ГРУППЫ, со ссылками на их адреса, и это
  // было ВОЗВРАЩЕНИЕМ УЖЕ ОТМЕНЁННОГО. Отмена записана этажом выше, в
  // `architect-page.tsx`: «прежнее умолчание (собрать ряд из разделов группы)
  // отменено вместе с `architectTabs`». Я не прочитал её и построил заново то,
  // что проект однажды уже убрал, — а владельцу пришлось повторять указание.
  //
  // 🛑 ПРИЗНАК, ПО КОТОРОМУ ЭТО ЛОВИТСЯ ЗАРАНЕЕ, ОДИН: если пункт ряда ведёт на
  // ДРУГОЙ адрес, он дублирует меню. Ряд имеет право вести только внутрь
  // текущего документа (`#якорь`), и тогда он отвечает на вопрос «что на этой
  // странице», а не «куда отсюда уйти».
  //
  // Плавность даёт `scroll-smooth` на `<html>`, а зазор под липкой полосой —
  // `scroll-mt-24` у заголовка; ни того ни другого здесь заводить не нужно.
  // Тем нет — ряда нет вовсе, и это законное состояние.
  const tabs: WorkspaceItem[] | undefined =
    (words.topics ?? []).length > 0
      ? (words.topics ?? []).map((t) => ({ label: t.tab, href: `#${t.anchor}` }))
      : undefined

  // Темы группы — её собственный текст из `_data`, разобранный так же, как у
  // страницы-раздела.
  //
  // 🪦 ДО 264-3 ИХ ЗДЕСЬ НЕ БЫЛО ВОВСЕ, И ЭТО БЫЛ ДЕФЕКТ, А НЕ УМОЛЧАНИЕ.
  // Рубрикатор молча выбрасывал `topics` своей страницы: пока ни у одной группы
  // текста не было, это ничего не ломало и потому не замечалось. В день, когда
  // текст у группы появился бы, он исчез бы целиком — ни ошибки, ни
  // предупреждения, ни следа в сборке. То же самое было у страницы-раздела и
  // вылечено в 264-2.
  //
  // 🔒 ПРИЗНАК КЛАССА, А НЕ ОДИН СЛУЧАЙ: оболочка, которая ВЫБИРАЕТ между двумя
  // источниками содержимого, однажды выберет не тот. Складывать безопаснее, чем
  // выбирать, — пустой источник ничего не добавляет.
  const fromTopics: Block[] = (words.topics ?? []).flatMap((t): Block[] => [
    { kind: 'h3', text: t.title, id: t.anchor },
    { kind: 'p', text: t.text },
    ...(t.points ? [{ kind: 'list' as const, items: t.points }] : []),
  ])

  // Своё содержимое встаёт ПЕРЕД перечнем: человек пришёл в группу за общим
  // взглядом, а список разделов — это то, куда он пойдёт дальше.
  const blocks: Block[] = [...(content ?? []), ...fromTopics, ...children]

  return (
    <ArchitectPage
      lang={lang}
      path={dir}
      pageTitle={words.title}
      pageLead={words.lead}
      title={words.title}
      tabs={tabs}
      children={blocks}
      widget={widget}
    />
  )
}
