'use client'

import { useEffect, useState } from 'react'

// ПОЛОСА: «ВЫ ВОШЛИ БЕЗ ПАРОЛЯ, ПОТОМУ ЧТО РАБОТАЕТЕ С ЭТОЙ МАШИНЫ» (2026-09-19).
//
// 🔒 ЗАЧЕМ ОНА НУЖНА — РЕШЕНИЕ ВЛАДЕЛЬЦА, выбравшего «по хозяину + полоса
// предупреждения». Допуск без входа выглядит как ОТСУТСТВИЕ защиты: человек
// открывает настройки узла, его никто не спросил, и он делает единственный
// возможный вывод — «значит и всем остальным открыто». Вывод неверный, а
// поведение из него следует опасное: он даст ссылку постороннему.
// Полоса превращает молчаливое поведение в объяснённое.
//
// 🔒 ОСТРОВОК, А НЕ СЕРВЕРНЫЙ КУСОК, И ЭТО НЕ КОМПРОМИСС. Страницы слоя
// статические; серверная проверка «кто пришёл» сделала бы динамическим весь слой
// одной строкой (`headers()`), ровно как запрещает закон о статике. Спрашивает
// островок после гидратации, у той же двери `/api/me`, что и замок слоя.
//
// 🛑 ПОЛОСА НИЧЕГО НЕ РЕШАЕТ И НИЧЕГО НЕ ОХРАНЯЕТ. Кого пускать — решает
// `getSession()` на сервере; здесь только объяснение человеку. Полоса, пытающаяся
// «на всякий случай» что-то закрыть, дала бы ложное чувство защиты в браузере,
// где защиты нет по природе.
export function OwnerBand({ text }: { text: string }) {
  const [показать, setПоказать] = useState(false)

  useEffect(() => {
    let живо = true
    fetch('/api/me')
      .then(r => (r.ok ? r.json() : null))
      .then((me: { viaMachine?: boolean } | null) => {
        if (живо) setПоказать(Boolean(me?.viaMachine))
      })
      .catch(() => {
        /* дверь не ответила — молчим: полоса не повод ломать страницу */
      })
    return () => {
      живо = false
    }
  }, [])

  if (!показать) return null

  return (
    <div
      role="status"
      className="mb-4 rounded-md border border-amber-500/30 bg-amber-500/10 px-3 py-2 text-[length:var(--fs-small)] text-amber-900 dark:text-amber-200"
    >
      {text}
    </div>
  )
}
