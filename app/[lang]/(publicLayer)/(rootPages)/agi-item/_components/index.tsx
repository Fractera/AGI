import { createContentPage } from '@/lib/content/create-content-page'
import { homePage, homeLead, data } from '../_data'
import { meta } from '../_data/meta'
import { PostBody } from '@/components/content-page/post-body'

// Вход главной страницы — ТА ЖЕ ФАБРИКА, ЧТО У ПРАВОВЫХ СТРАНИЦ.
//
// 🔒 ЗДЕСЬ ЕДВА НЕ ПОЯВИЛСЯ ВТОРОЙ СТАНДАРТ (шаг 508 FNS, поймано владельцем).
// Сначала главная получила свой вход: «у лендинга другая анатомия». Проверка
// показала, что это неправда — из пятнадцати свойств шаблона четырнадцать
// исчезали сами, когда их не дают. Оговорка сохранена намеренно: соблазн завести
// отдельную фабрику вернётся вместе с настоящим лендингом.
//
// 🔒 ВЕРХНЯЯ ЧАСТЬ СТРАНИЦЫ ОБЪЯВЛЕНА СТАНДАРТНОЙ (231-1, слово владельца по
// образцу memory.aifa.dev): ярлык → H1 → подзаголовок → короткий абзац → ряд
// значков → два действия → оглавление. Первые три печатает шапка страницы,
// следующие три — слот `afterHeader`, оглавление строит фабрика сама.
//
// ✗ ОПЛАЧЕНО В ЭТОМ ЖЕ ПОДШАГЕ: сперва значки уехали в `afterHero` и встали ВЫШЕ
// собственного заголовка страницы, а до того — не нарисовались нигде, потому что
// поднятый вид без слота, который его рисует, исчезает молча. Ни одна проверка
// при этом не падает.
// 🪦 БАННЕР СТАРТОВОГО ШАБЛОНА УДАЛЁН 2026-09-18 ПО СЛОВУ ВЛАДЕЛЬЦА («not need —
// remove it»). Он висел поверх страницы в слоте `afterHero` и звал «подключите
// ваш репозиторий и перейдите к разработке». Зов в разработку противоречит тому,
// чем стал этот сайт: человек получает РАБОТАЮЩИЙ САЙТ в продакшне, а не проект,
// который ещё надо доделать. Вместе с вызовом удалены `starter-banner.client.tsx`
// и `starter-banner.i18n.ts` — они существовали только ради него; вернуть можно
// из git.
const page = createContentPage({
  // Языки, на которых у страницы есть СВОЙ текст (256-6).
  data,
  resolve: homePage,
  meta,
  // 🔒 ЗАГОЛОВОК ПЕЧАТАЕТ ПЕРВЫЙ ЭКРАН, А НЕ ШАПКА — то же, что на главной.
  //
  // ✗ ПОЙМАНО ЗАМЕРОМ 2026-09-20: после перехода страницы на вид `heroSplit` на
  // ней оказалось ДВА H1 с одним и тем же текстом — один от шапки, другой от
  // первого экрана. Глазами это выглядит просто как повтор заголовка; для
  // поисковика два H1 спорят между собой, и страница теряет собственную тему.
  titleInBody: true,
  // Верхняя часть: поднятые виды — значки и действия.
  //
  // 🪦 ЗДЕСЬ ЖЕ ПЕЧАТАЛСЯ АБЗАЦ `intro` («ядро намеренно мало…»). Поле убрано
  // 2026-09-20: текст переехал в цитату внутри страницы, где читается как
  // утверждение о замысле, а не как продолжение подзаголовка.
  afterHeader: (lang: string) => <PostBody blocks={homeLead(lang)} lang={lang} />,
})

export const generateMetadata = page.generateMetadata
export default page.Page
